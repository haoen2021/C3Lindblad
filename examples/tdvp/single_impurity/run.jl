mutable struct TruncationObserver
    maximum::Float64
    cumulative::Float64
    events::Int
end

function ITensorMPS.update_observer!(obs::TruncationObserver; spec = nothing, kwargs...)
    if !isnothing(spec)
        error = truncerror(spec)
        obs.maximum = max(obs.maximum, error)
        obs.cumulative += error
        obs.events += 1
    end
    return obs
end

complex_table(z) = Dict("real" => Float64(real(z)), "imag" => Float64(imag(z)))

