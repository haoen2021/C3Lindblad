    mkpath(dirname(path))
    open(path, "w") do io
        TOML.print(io, table; sorted = true)
    end
end

function write_response(path, t, add_up, rem_up, add_dn, rem_dn)
    open(path, "w") do io
        println(
            io,
            "time,G_add_up_real,G_add_up_imag,G_remove_up_real,G_remove_up_imag," *
            "G_add_down_real,G_add_down_imag,G_remove_down_real,G_remove_down_imag," *
            "G_add_spin_average_real,G_add_spin_average_imag," *
            "G_remove_spin_average_real,G_remove_spin_average_imag," *
            "G_retarded_real,G_retarded_imag",
        )
        for j in eachindex(t)
            add = (add_up[j] + add_dn[j]) / 2
            rem = (rem_up[j] + rem_dn[j]) / 2
            total = add + rem
            println(
                io,
                join(
                    (
                        t[j], real(add_up[j]), imag(add_up[j]), real(rem_up[j]),
                        imag(rem_up[j]), real(add_dn[j]), imag(add_dn[j]),
                        real(rem_dn[j]), imag(rem_dn[j]), real(add), imag(add),
                        real(rem), imag(rem), real(total), imag(total),
                    ),
                    ',',
                ),
            )
        end
    end
end

function gauss_legendre(order)
    offdiagonal = [j / sqrt(4j^2 - 1) for j in 1:(order - 1)]
    eig = eigen(SymTridiagonal(zeros(order), offdiagonal))
    return eig.values, 2 .* abs2.(eig.vectors[1, :])
end

"""Separate Gauss--Legendre nodes on [-W,0] and [0,W]."""
function fermi_edge_quadrature(m; W, Gamma)
    iseven(m) || error("the zero-temperature bath size must be even")
    x, w = gauss_legendre(m ÷ 2)
    omega = vcat(W .* (x .- 1) ./ 2, W .* (x .+ 1) ./ 2)
    measure = vcat(W .* w ./ 2, W .* w ./ 2)
    J = Gamma / pi .* sqrt.(max.(0.0, 1 .- (omega ./ W) .^ 2))
    return omega, measure .* J
end

"""Target correlation from a high-order half-band quadrature."""
function target_correlation(t; W, Gamma, lesser, order = 1024)
    omega, weight = fermi_edge_quadrature(2order; W, Gamma)
    out = zeros(ComplexF64, length(t))
    for j in eachindex(omega)
        occupied = omega[j] < 0
        if occupied == lesser
            out .+= weight[j] .* exp.(-im .* omega[j] .* t)
        end
    end
    return out
end

"""Correlation generated by the finite star before its exact chain mapping."""
function finite_bath_correlation(t; m, W, Gamma, lesser)
    omega, weight = fermi_edge_quadrature(m; W, Gamma)
    out = zeros(ComplexF64, length(t))
    for j in eachindex(omega)
        if (omega[j] < 0) == lesser
            out .+= weight[j] .* exp.(-im .* omega[j] .* t)
        end
    end
    return out
end

"""Lanczos map diag(omega),sqrt(weight) to one nearest-neighbor chain."""
function chain_parameters(m; W, Gamma)
    omega, weight = fermi_edge_quadrature(m; W, Gamma)
    coupling = sqrt(sum(weight))
    q = sqrt.(weight) ./ coupling
    prior = zeros(Float64, m)
    onsite = zeros(Float64, m)
    hopping = zeros(Float64, m - 1)
    beta = 0.0
    for j in 1:m
        r = omega .* q .- beta .* prior
        onsite[j] = dot(q, r)
        r .-= onsite[j] .* q
        if j < m
            hopping[j] = norm(r)
            hopping[j] > 100eps(Float64) || error("bath-chain Lanczos breakdown")
            prior, q = q, r ./ hopping[j]
            beta = hopping[j]
        end
    end
    return coupling, onsite, hopping
end

function correlation_error(observed, target, t)
    dt = diff(t)
    integral(v) = sum(dt .* (v[1:(end - 1)] .+ v[2:end]) ./ 2)
    relative = sqrt(integral(abs2.(observed - target)) / integral(abs2.(target)))
    return relative, maximum(abs.(observed - target))
end

function write_bath_data(output, t, target_l, target_g, finite_l, finite_g)
    open(joinpath(output, "bath_correlations.csv"), "w") do io
        println(
            io,
            "time,target_lesser_real,target_lesser_imag,target_greater_real," *
            "target_greater_imag,finite_lesser_real,finite_lesser_imag," *
            "finite_greater_real,finite_greater_imag",
        )
        for j in eachindex(t)
            println(
                io,
                join(
                    (
                        t[j], real(target_l[j]), imag(target_l[j]), real(target_g[j]),
                        imag(target_g[j]), real(finite_l[j]), imag(finite_l[j]),
                        real(finite_g[j]), imag(finite_g[j]),
                    ),
                    ',',
                ),
            )
        end
    end
end

function build_hamiltonian(sites; U, W, Gamma)
    L = length(sites)
    V, onsite, hopping = chain_parameters(L - 1; W, Gamma)
    epsilon = -U / 2
    os = OpSum()
    os += epsilon, "Nup", 1
    os += epsilon, "Ndn", 1
    os += U, "Nupdn", 1
    for spin in ("up", "dn")
        create = spin == "up" ? "Cdagup" : "Cdagdn"
        destroy = spin == "up" ? "Cup" : "Cdn"
        os += -V, create, 1, destroy, 2
        os += -V, create, 2, destroy, 1
        for j in 1:(L - 1)
            os += onsite[j], spin == "up" ? "Nup" : "Ndn", j + 1
        end
        for j in 2:(L - 1)
            os += -hopping[j - 1], create, j, destroy, j + 1
            os += -hopping[j - 1], create, j + 1, destroy, j
        end
    end
    return MPO(os, sites)
end

function initial_state(L)
    # L is odd. This product has N_up=(L+1)/2 and N_down=(L-1)/2.
    state = fill("Emp", L)
    state[1] = "Up"
    for j in 2:2:(L - 1)
        state[j] = "UpDn"
    end
    return state
end

function impurity_source(psi, sites, name)
    # The impurity is the first chain site, so its Jordan--Wigner string is
    # empty. ITensor's Electron operator supplies the on-site spin sign.
    source = deepcopy(psi)
    source[1] = apply(op(name, sites[1]), source[1])
    return source
end

function ground_state(config, output)
    model = config["model"]
    dmrg_config = config["dmrg"]
    m = Int(model["bath_sites_per_spin"])
    L = m + 1
    U = Float64(model["U"])
    W = Float64(model["W"])
    Gamma = Float64(model["Gamma"])
    sites = siteinds("Electron", L; conserve_qns = true)
    H = build_hamiltonian(sites; U, W, Gamma)

    initial_checkpoint = String(get(dmrg_config, "initial_checkpoint", ""))
    if isempty(initial_checkpoint)
        psi0 = random_mps(
            sites,
            initial_state(L);
            linkdims = Int(dmrg_config["initial_link_dimension"]),
        )
    else
        saved = open(deserialize, joinpath(ROOT, initial_checkpoint))
        length(saved.sites) == L || error("initial checkpoint has a different bath size")
        sites = saved.sites
        H = build_hamiltonian(sites; U, W, Gamma)
        psi0 = saved.psi
    end

    nsweeps = Int(dmrg_config["sweeps"])
    maxdim_schedule = Int.(dmrg_config["maxdim_schedule"])
    noise_schedule = Float64.(dmrg_config["noise_schedule"])
    cutoff = Float64(dmrg_config["cutoff"])
    observer = DMRGObserver(; energy_tol = 1e-10, minsweeps = min(6, nsweeps))
    started = time()
    energy, psi = dmrg(
        H,
        psi0;
        nsweeps,
        maxdim = maxdim_schedule,
        cutoff,
        noise = noise_schedule,
        observer,
        outputlevel = 1,
    )
    wall = time() - started
    norm_squared = real(inner(psi, psi))
    mean_energy = real(inner(psi', H, psi)) / norm_squared
    second_energy_moment = real(inner(H, psi, H, psi)) / norm_squared
    variance = max(second_energy_moment - mean_energy^2, 0.0)
    energy_standard_deviation = sqrt(variance)
    n_up = expect(psi, "Nup"; sites = 1)
    n_down = expect(psi, "Ndn"; sites = 1)
    double_occupancy = expect(psi, "Nupdn"; sites = 1)
    checkpoint = joinpath(output, "ground_state.jls")
    open(checkpoint, "w") do io
        serialize(io, (; sites, psi, energy, U, W, Gamma, bath_sites = m))
    end
    result = Dict(
        "U" => U,
        "epsilon_d" => -U / 2,
        "bath_sites_per_spin" => m,
        "bath_spin_orbitals_total" => 2m,
        "particle_sector" => Dict("N_up" => (L + 1) ÷ 2, "N_down" => (L - 1) ÷ 2),
        "energy" => Float64(real(energy)),
        "independently_evaluated_energy" => Float64(mean_energy),
        "state_norm_squared" => Float64(norm_squared),
        "energy_variance" => Float64(variance),
        "energy_standard_deviation" => Float64(energy_standard_deviation),
        "energy_by_sweep" => Float64.(real.(energies(observer))),
        "maximum_discarded_weight_by_sweep" => Float64.(truncerrors(observer)),
        "actual_maximum_bond_dimension" => maxlinkdim(psi),
        "impurity_n_up" => Float64(real(n_up)),
        "impurity_n_down" => Float64(real(n_down)),
        "impurity_double_occupancy" => Float64(real(double_occupancy)),
        "wall_seconds" => wall,
        "peak_rss_bytes" => Sys.maxrss(),
        "checkpoint" => relpath(checkpoint, ROOT),
    )
    write_toml(joinpath(output, "ground_state.toml"), result)
    return result
end

function tdvp_step(
    H, psi; dt, cutoff, maxdim, nsite, updater_krylovdim, updater_tolerance
)
    observer = TruncationObserver(0.0, 0.0, 0)
    started = time()
    next = tdvp(
        H,
        -im * dt,
        psi;
        time_step = -im * dt,
        nsite,
        cutoff,
        maxdim,
        normalize = false,
        reverse_step = true,
        (observer!) = observer,
        updater_kwargs = (;
            tol = updater_tolerance, krylovdim = updater_krylovdim, maxiter = 100
        ),
        outputlevel = 0,
    )
    return (
        next,
        observer.maximum,
        observer.cumulative,
        observer.events,
        maxlinkdim(next),
        time() - started,
    )
end

function impurity_matrix_element(left, right, sites, name)
    acted = copy(right)
    acted[1] = apply(op(name, sites[1]), right[1])
    return inner(left, acted)
end

function expand_tdvp_basis(state, H; krylovdim, cutoff, maxdim)
    started = time()
    expanded = expand(
        state,
        H;
        alg = "global_krylov",
        krylovdim,
        cutoff,
        apply_kwargs = (; cutoff, maxdim),
    )
    truncate!(expanded; cutoff, maxdim)
    fidelity = abs(inner(state, expanded)) / sqrt(abs(inner(state, state) * inner(expanded, expanded)))
    return expanded, fidelity, time() - started
end

function response_trajectory(
    H, psi, sites, t;
    dt, cutoff, maxdim, nsite, checkpoint_path = nothing, checkpoint_interval = 10,
    expansion_krylovdim = 0, expansion_cutoff = cutoff, updater_krylovdim = 8,
    updater_tolerance = 1.0e-12,
    independent_addition_pair = false, initial_neutral = nothing, initial_states = nothing,
)
    neutral = isnothing(initial_neutral) ? deepcopy(psi) : deepcopy(initial_neutral)
    states = Dict{String, MPS}()
    if isnothing(initial_states)
        for spin in ("up", "down")
            states["addition_$spin"] = impurity_source(
                psi, sites, spin == "up" ? "Cdagup" : "Cdagdn"
            )
            if !independent_addition_pair
                states["removal_$spin"] = impurity_source(
                    psi, sites, spin == "up" ? "Cup" : "Cdn"
                )
            end
        end
    else
        for (name, state) in initial_states
            states[String(name)] = deepcopy(state)
        end
    end
    expansion_fidelity = Dict{String, Float64}()
    expansion_wall = Dict{String, Float64}()
    if expansion_krylovdim > 0
        neutral, fidelity, wall = expand_tdvp_basis(
            neutral, H; krylovdim = expansion_krylovdim, cutoff = expansion_cutoff, maxdim
        )
        expansion_fidelity["neutral"] = fidelity
        expansion_wall["neutral"] = wall
        for name in keys(states)
            states[name], fidelity, wall = expand_tdvp_basis(
                states[name],
                H;
                krylovdim = expansion_krylovdim,
                cutoff = expansion_cutoff,
                maxdim,
            )
            expansion_fidelity[name] = fidelity
            expansion_wall[name] = wall
        end
    end
    values = Dict(
        name => Vector{ComplexF64}(undef, length(t)) for name in keys(states)
    )
    discarded = Dict(name => 0.0 for name in keys(states))
    cumulative_discarded = Dict(name => 0.0 for name in keys(states))
    truncation_events = Dict(name => 0 for name in keys(states))
    bonds = Dict(name => maxlinkdim(state) for (name, state) in states)
    walls = Dict(name => 0.0 for name in keys(states))
    neutral_discarded = 0.0
    neutral_cumulative_discarded = 0.0
    neutral_truncation_events = 0
    neutral_bond = maxlinkdim(neutral)
    neutral_wall = 0.0
    neutral_norm_squared = Vector{Float64}(undef, length(t))
    neutral_energy = Vector{Float64}(undef, length(t))
    state_norm_squared = Dict(
        name => Vector{Float64}(undef, length(t)) for name in keys(states)
    )
    started = time()
    for j in eachindex(t)
        neutral_norm_squared[j] = real(inner(neutral, neutral))
        neutral_energy[j] = real(inner(neutral', H, neutral)) / neutral_norm_squared[j]
        for (name, state) in states
            state_norm_squared[name][j] = real(inner(state, state))
            spin = endswith(name, "up") ? "up" : "down"
            destroy = spin == "up" ? "Cup" : "Cdn"
            if startswith(name, "addition")
                values[name][j] = -im * impurity_matrix_element(
                    neutral, state, sites, destroy
                )
            else
                values[name][j] = -im * impurity_matrix_element(
                    state, neutral, sites, destroy
                )
            end
        end
        j == lastindex(t) && break
        neutral, truncation, cumulative, events, bond, wall = tdvp_step(
            H, neutral; dt, cutoff, maxdim, nsite, updater_krylovdim, updater_tolerance
        )
        neutral_discarded = max(neutral_discarded, truncation)
        neutral_cumulative_discarded += cumulative
        neutral_truncation_events += events
        neutral_bond = max(neutral_bond, bond)
        neutral_wall += wall
        for name in keys(states)
            states[name], truncation, cumulative, events, bond, wall = tdvp_step(
                H, states[name];
                dt,
                cutoff,
                maxdim,
                nsite,
                updater_krylovdim,
                updater_tolerance,
            )
            discarded[name] = max(discarded[name], truncation)
            cumulative_discarded[name] += cumulative
            truncation_events[name] += events
            bonds[name] = max(bonds[name], bond)
            walls[name] += wall
        end
        if !isnothing(checkpoint_path) && (j % checkpoint_interval == 0)
            open(checkpoint_path, "w") do io
                serialize(io, (; completed_step = j, t, values, neutral, states))
            end
        end
    end
    diagnostics = Dict(
        "neutral_maximum_discarded_weight" => neutral_discarded,
        "neutral_cumulative_discarded_weight" => neutral_cumulative_discarded,
        "neutral_truncation_event_count" => neutral_truncation_events,
        "neutral_actual_maximum_bond_dimension" => neutral_bond,
        "neutral_wall_seconds" => neutral_wall,
        "neutral_norm_squared_by_time" => neutral_norm_squared,
        "neutral_maximum_norm_drift" => maximum(abs.(neutral_norm_squared .- neutral_norm_squared[1])),
        "neutral_energy_by_time" => neutral_energy,
        "neutral_maximum_energy_drift" => maximum(abs.(neutral_energy .- neutral_energy[1])),
        "basis_expansion_krylov_dimension" => expansion_krylovdim,
        "local_updater_krylov_dimension" => updater_krylovdim,
        "local_updater_tolerance" => updater_tolerance,
        "basis_expansion_fidelity" => expansion_fidelity,
        "basis_expansion_wall_seconds" => expansion_wall,
        "response_maximum_discarded_weight" => discarded,
        "response_cumulative_discarded_weight" => cumulative_discarded,
        "response_truncation_event_count" => truncation_events,
        "response_actual_maximum_bond_dimension" => bonds,
        "response_norm_squared_by_time" => state_norm_squared,
        "response_maximum_norm_drift" => Dict(
            name => maximum(abs.(norms .- norms[1]))
            for (name, norms) in state_norm_squared
        ),
        "response_wall_seconds" => walls,
        "wall_seconds" => time() - started,
    )
    return values, neutral, states, diagnostics
end

function response(config, output)
    model = config["model"]
    response_config = config["tdvp"]
    checkpoint_path = joinpath(ROOT, String(response_config["ground_checkpoint"]))
    saved = open(deserialize, checkpoint_path)
    U = Float64(model["U"])
    U == saved.U || error("ground-state checkpoint interaction differs")
    sites = saved.sites
    psi = deepcopy(saved.psi)
    H = build_hamiltonian(
        sites;
        U,
        W = Float64(model["W"]),
        Gamma = Float64(model["Gamma"]),
    )
    dt = Float64(response_config["dt"])
    tmax = Float64(response_config["tmax"])
    resume_path = String(get(response_config, "resume_checkpoint", ""))
    start_time = 0.0
    initial_neutral = nothing
    initial_states = nothing
    if !isempty(resume_path)
        resumed = open(deserialize, joinpath(ROOT, resume_path))
        resumed.U == U || error("response checkpoint interaction differs")
        start_time = Float64(last(resumed.t))
        initial_neutral = resumed.neutral
        initial_states = resumed.final_states
    end
    duration = tmax - start_time
    duration >= 0 || error("tmax precedes the response checkpoint time")
    steps = round(Int, duration / dt)
    isapprox(steps * dt, duration; atol = 100eps(Float64), rtol = 0.0) ||
        error("the response interval must be an integer multiple of dt")
    t = collect(range(start_time, tmax; length = steps + 1))
    cutoff = Float64(response_config["cutoff"])
    maxdim = Int(response_config["maxdim"])
    initial_projection = Dict{String, Any}(
        "applied" => false,
        "source_ground_maximum_bond_dimension" => maxlinkdim(psi),
        "response_maximum_bond_dimension" => maxdim,
        "fidelity" => 1.0,
        "norm_before_normalization" => Float64(norm(psi)),
    )
    if isempty(resume_path)
        original = deepcopy(psi)
        original_norm = norm(original)
        truncate!(psi; cutoff, maxdim)
        truncated_norm = norm(psi)
        fidelity = abs(inner(original, psi)) / (original_norm * truncated_norm)
        psi[1] *= inv(truncated_norm)
        initial_projection = Dict(
            "applied" => maxlinkdim(original) > maxdim,
            "source_ground_maximum_bond_dimension" => maxlinkdim(original),
            "response_maximum_bond_dimension" => maxdim,
            "fidelity" => Float64(fidelity),
            "norm_before_normalization" => Float64(truncated_norm),
        )
    end
    nsite = Int(get(response_config, "nsite", 2))
    nsite in (1, 2) || error("TDVP nsite must be one or two")
    checkpoint_interval = Int(get(response_config, "checkpoint_interval_steps", 10))
    expansion_krylovdim = Int(get(response_config, "basis_expansion_krylov_dimension", 0))
    expansion_cutoff = Float64(get(response_config, "basis_expansion_cutoff", cutoff))
    updater_krylovdim = Int(get(response_config, "updater_krylov_dimension", 8))
    updater_tolerance = Float64(get(response_config, "updater_tolerance", 1.0e-12))
    branch_mode = String(get(response_config, "branch_mode", "all_four"))
    branch_mode in ("all_four", "addition_pair_particle_hole") ||
        error("branch_mode must be all_four or addition_pair_particle_hole")
    independent_addition_pair = branch_mode == "addition_pair_particle_hole"
    progress_path = joinpath(output, "response_progress.jls")
    values, neutral, final_states, trajectory = response_trajectory(
        H,
        psi,
        sites,
        t;
        dt,
        cutoff,
        maxdim,
        nsite,
        checkpoint_path = progress_path,
        checkpoint_interval,
        expansion_krylovdim,
        expansion_cutoff,
        updater_krylovdim,
        updater_tolerance,
        independent_addition_pair,
        initial_neutral,
        initial_states,
    )
    if independent_addition_pair
        # At particle-hole symmetry, the finite chain obeys
        # G^-_up(t)=-conj(G^+_down(t)) and G^-_down(t)=-conj(G^+_up(t)).
        values["removal_up"] = -conj.(values["addition_down"])
        values["removal_down"] = -conj.(values["addition_up"])
    end
    write_response(
        joinpath(output, "retarded_green_time.csv"),
        t,
        values["addition_up"],
        values["removal_up"],
        values["addition_down"],
        values["removal_down"],
    )
    response_checkpoint = joinpath(output, "response_final_states.jls")
    open(response_checkpoint, "w") do io
        serialize(io, (; t, values, neutral, final_states, U, dt, cutoff, maxdim, branch_mode))
    end
    add = (values["addition_up"] + values["addition_down"]) / 2
    rem = (values["removal_up"] + values["removal_down"]) / 2
    total = add + rem
    channels = Dict{String, Any}()
    for spin in ("up", "down")
        channel = Dict(
            "addition_norm" => norm(impurity_source(
                psi, sites, spin == "up" ? "Cdagup" : "Cdagdn"
            ))^2,
            "removal_norm" => norm(impurity_source(
                psi, sites, spin == "up" ? "Cup" : "Cdn"
            ))^2,
            "initial_sample_time" => first(t),
            "initial_sample_sum" => complex_table(
                values["addition_$spin"][1] + values["removal_$spin"][1]
            ),
        )
        if iszero(start_time)
            channel["equal_time_sum"] = channel["initial_sample_sum"]
        end
        channels[spin] = channel
    end
    result = Dict(
        "U" => U,
        "dt" => dt,
        "start_time" => start_time,
        "tmax" => tmax,
        "cutoff" => cutoff,
        "maxdim" => maxdim,
        "nsite" => nsite,
        "formulation" => "co-propagated neutral and odd source MPSs; no scalar ground-state phase approximation",
        "checkpoint_interval_steps" => checkpoint_interval,
        "basis_expansion_krylov_dimension" => expansion_krylovdim,
        "basis_expansion_cutoff" => expansion_cutoff,
        "local_updater_krylov_dimension" => updater_krylovdim,
        "local_updater_tolerance" => updater_tolerance,
        "branch_mode" => branch_mode,
        "branch_reconstruction" => independent_addition_pair ?
            "removal_up=-conj(addition_down); removal_down=-conj(addition_up)" :
            "none; all four channels propagated",
        "resume_checkpoint" => resume_path,
        "initial_ground_projection" => initial_projection,
        "trajectory" => trajectory,
        "channels" => channels,
        "initial_sample_spin_average" => complex_table(total[1]),
        "particle_hole_spin_averaged_defect" => maximum(abs.(add + conj.(rem))),
        "wall_seconds" => trajectory["wall_seconds"],
        "peak_rss_bytes" => Sys.maxrss(),
        "ground_checkpoint" => relpath(checkpoint_path, ROOT),
        "response_checkpoint" => relpath(response_checkpoint, ROOT),
    )
    if iszero(start_time)
        result["equal_time_spin_average"] = result["initial_sample_spin_average"]
    end
    write_toml(joinpath(output, "response.toml"), result)
    return result
end

function bath_gate(config, output)
    model = config["model"]
    m = Int(model["bath_sites_per_spin"])
    W = Float64(model["W"])
    Gamma = Float64(model["Gamma"])
    t = collect(range(0.0, 4.0; step = 0.005))
    target_l = target_correlation(t; W, Gamma, lesser = true)
    target_g = target_correlation(t; W, Gamma, lesser = false)
    finite_l = finite_bath_correlation(t; m, W, Gamma, lesser = true)
    finite_g = finite_bath_correlation(t; m, W, Gamma, lesser = false)
    lesser_relative, lesser_maximum = correlation_error(finite_l, target_l, t)
    greater_relative, greater_maximum = correlation_error(finite_g, target_g, t)
    write_bath_data(output, t, target_l, target_g, finite_l, finite_g)
    result = Dict(
        "bath_sites_per_spin" => m,
        "bath_spin_orbitals_total" => 2m,
        "W" => W,
        "Gamma" => Gamma,
        "mu" => 0.0,
        "temperature" => "beta=infinity",
        "discretization" => "20-point Gauss-Legendre on each Fermi half-band, exact Lanczos chain map",
        "chain_impurity_coupling" => chain_parameters(m; W, Gamma)[1],
        "chain_bath_hopping_minimum" => minimum(chain_parameters(m; W, Gamma)[3]),
        "chain_bath_hopping_maximum" => maximum(chain_parameters(m; W, Gamma)[3]),
        "lesser_complex_relative_L2" => lesser_relative,
        "greater_complex_relative_L2" => greater_relative,
        "lesser_maximum_absolute" => lesser_maximum,
        "greater_maximum_absolute" => greater_maximum,
    )
    write_toml(joinpath(output, "bath_gate.toml"), result)
    return result
end

function analytic_u0(config, output)
    model = config["model"]
    m = Int(model["bath_sites_per_spin"])
    W = Float64(model["W"])
    Gamma = Float64(model["Gamma"])
    coupling, onsite, hopping = chain_parameters(m; W, Gamma)
    h = zeros(Float64, m + 1, m + 1)
    h[1, 2] = h[2, 1] = -coupling
    for j in 1:m
        h[j + 1, j + 1] = onsite[j]
    end
    for j in 2:m
        h[j, j + 1] = h[j + 1, j] = -hopping[j - 1]
    end
    eig = eigen(Symmetric(h))
    t = collect(range(0.0, 4.0; step = 0.05))
    green = -im .* [
        sum(abs2.(eig.vectors[1, :]) .* exp.(-im .* eig.values .* value))
        for value in t
    ]
    open(joinpath(output, "analytic_U0_green.csv"), "w") do io
        println(io, "time,G_retarded_real,G_retarded_imag")
        for j in eachindex(t)
            println(io, "$(t[j]),$(real(green[j])),$(imag(green[j]))")
        end
    end
    result = Dict(
        "equal_time" => complex_table(green[1]),
        "maximum_real_particle_hole_defect" => maximum(abs.(real.(green))),
    )
    write_toml(joinpath(output, "analytic_U0.toml"), result)
    return result
end

function main()
